fn validate_illustrator_xml_internal(
    xml_str: &str,
    expected_datasets: usize,
    explicit_text_vars: Option<&[&str]>,
    explicit_linked_vars: Option<&[&str]>,
) {
    assert!(
        xml_str.starts_with("<?xml version=\"1.0\" encoding=\"utf-8\"?>"),
        "XML must start with UTF-8 XML declaration"
    );

    let mut reader = Reader::from_str(xml_str);
    reader.config_mut().check_end_names = true;
    reader.config_mut().check_comments = true;
    reader.config_mut().allow_dangling_amp = false;
    reader.config_mut().allow_unmatched_ends = false;

    let mut saw_decl = false;
    let mut saw_doctype = false;
    let mut dtd_entities: HashMap<String, String> = HashMap::new();
    let mut tag_stack: Vec<String> = Vec::new();
    let mut var_traits: HashMap<String, String> = HashMap::new();
    let mut dataset_count = 0usize;
    let mut dataset_names: HashSet<String> = HashSet::new();

    // (tag_name, is_text, is_linked, p_child_count, direct_text)
    struct FieldState {
        tag_name: String,
        is_text: bool,
        is_linked: bool,
        p_child_count: usize,
        direct_text: String,
    }
    let mut current_field: Option<FieldState> = None;

    let text_override: Option<HashSet<&str>> =
        explicit_text_vars.map(|s| s.iter().copied().collect());
    let linked_override: Option<HashSet<&str>> =
        explicit_linked_vars.map(|s| s.iter().copied().collect());

    loop {
        match reader.read_event().expect("quick_xml parse error") {
            Event::Decl(_) => {
                saw_decl = true;
            }
            Event::DocType(dt) => {
                saw_doctype = true;
                let dt_text = dt.decode().expect("decode DOCTYPE");
                dtd_entities = extract_dtd_entities(&dt_text);
                for required_ent in [
                    "ns_graphs",
                    "ns_vars",
                    "ns_imrep",
                    "ns_custom",
                    "ns_flows",
                    "ns_extend",
                ] {
                    assert!(
                        dtd_entities.contains_key(required_ent),
                        "DOCTYPE missing Adobe entity &{required_ent};"
                    );
                }
            }
            Event::Start(e) => {
                let tag = String::from_utf8(e.name().as_ref().to_vec()).expect("utf8 tag");
                let mut attr_map: HashMap<String, String> = HashMap::new();
                for attr_res in e.attributes() {
                    let attr = attr_res.expect("malformed attribute");
                    let key =
                        String::from_utf8(attr.key.as_ref().to_vec()).expect("utf8 attr key");
                    assert!(
                        !attr.value.contains(&b'<'),
                        "unescaped '<' in attribute {key}"
                    );
                    let val = attr
                        .decoded_and_normalized_value_with(
                            XmlVersion::Implicit1_0,
                            e.decoder(),
                            128,
                            |ent| {
                                resolve_predefined_entity(ent)
                                    .or_else(|| dtd_entities.get(ent).map(String::as_str))
                            },
                        )
                        .expect("invalid escape or unrecognized entity in attribute");
                    attr_map.insert(key, val.into_owned());
                }

                if tag == "variable" {
                    if let (Some(vn), Some(tr)) = (attr_map.get("varName"), attr_map.get("trait"))
                    {
                        var_traits.insert(vn.clone(), tr.clone());
                    }
                } else if tag == "v:sampleDataSet" || tag == "sampleDataSet" {
                    dataset_count += 1;
                    let ds_name = attr_map
                        .get("dataSetName")
                        .expect("sampleDataSet missing dataSetName");
                    assert!(!ds_name.is_empty(), "dataSetName must be non-empty");
                    assert!(
                        dataset_names.insert(ds_name.clone()),
                        "duplicate dataSetName '{ds_name}'"
                    );
                } else if tag_stack
                    .last()
                    .is_some_and(|p| p == "v:sampleDataSet" || p == "sampleDataSet")
                {
                    let is_linked = linked_override
                        .as_ref()
                        .map(|s| s.contains(tag.as_str()))
                        .unwrap_or_else(|| {
                            var_traits.get(&tag).map(String::as_str) == Some("fileref")
                        });
                    let is_text = text_override
                        .as_ref()
                        .map(|s| s.contains(tag.as_str()))
                        .unwrap_or_else(|| {
                            var_traits.get(&tag).map(String::as_str) == Some("textcontent")
                        });
                    current_field = Some(FieldState {
                        tag_name: tag.clone(),
                        is_text,
                        is_linked,
                        p_child_count: 0,
                        direct_text: String::new(),
                    });
                } else if let Some(field) = current_field.as_mut() {
                    if tag == "p" {
                        assert!(
                            !field.is_linked,
                            "LinkedFile field <{}> must NOT contain <p>",
                            field.tag_name
                        );
                        field.p_child_count += 1;
                    }
                }

                tag_stack.push(tag);
            }
            Event::Empty(e) => {
                let tag = String::from_utf8(e.name().as_ref().to_vec()).expect("utf8 tag");
                let mut attr_map: HashMap<String, String> = HashMap::new();
                for attr_res in e.attributes() {
                    let attr = attr_res.expect("malformed attribute");
                    let key =
                        String::from_utf8(attr.key.as_ref().to_vec()).expect("utf8 attr key");
                    assert!(
                        !attr.value.contains(&b'<'),
                        "unescaped '<' in attribute {key}"
                    );
                    let val = attr
                        .decoded_and_normalized_value_with(
                            XmlVersion::Implicit1_0,
                            e.decoder(),
                            128,
                            |ent| {
                                resolve_predefined_entity(ent)
                                    .or_else(|| dtd_entities.get(ent).map(String::as_str))
                            },
                        )
                        .expect("invalid escape or unrecognized entity in attribute");
                    attr_map.insert(key, val.into_owned());
                }

                if tag == "variable" {
                    if let (Some(vn), Some(tr)) = (attr_map.get("varName"), attr_map.get("trait"))
                    {
                        var_traits.insert(vn.clone(), tr.clone());
                    }
                } else if tag == "v:sampleDataSet" || tag == "sampleDataSet" {
                    dataset_count += 1;
                    let ds_name = attr_map
                        .get("dataSetName")
                        .expect("sampleDataSet missing dataSetName");
                    assert!(!ds_name.is_empty(), "dataSetName must be non-empty");
                    assert!(
                        dataset_names.insert(ds_name.clone()),
                        "duplicate dataSetName '{ds_name}'"
                    );
                } else if tag_stack
                    .last()
                    .is_some_and(|p| p == "v:sampleDataSet" || p == "sampleDataSet")
                {
                    let is_text = text_override
                        .as_ref()
                        .map(|s| s.contains(tag.as_str()))
                        .unwrap_or_else(|| {
                            var_traits.get(&tag).map(String::as_str) == Some("textcontent")
                        });
                    assert!(
                        !is_text,
                        "Text field <{tag}/> cannot be empty without <p></p>"
                    );
                } else if let Some(field) = current_field.as_mut() {
                    if tag == "p" {
                        assert!(
                            !field.is_linked,
                            "LinkedFile field <{}> must NOT contain <p/>",
                            field.tag_name
                        );
                        field.p_child_count += 1;
                    }
                }
            }
            Event::Text(t) => {
                let txt = t.xml10_content().expect("invalid XML 1.0 text content");
                if let Some(field) = current_field.as_mut() {
                    if tag_stack.last().map(String::as_str) == Some(field.tag_name.as_str()) {
                        field.direct_text.push_str(&txt);
                    }
                }
            }
            Event::GeneralRef(r) => {
                if r.is_char_ref() {
                    r.resolve_char_ref().expect("invalid XML char ref");
                } else {
                    let name = r.decode().expect("utf8 entity ref");
                    assert!(
                        resolve_predefined_entity(&name).is_some()
                            || dtd_entities.contains_key(name.as_ref()),
                        "unrecognized XML entity &{name};"
                    );
                }
            }
            Event::End(e) => {
                let tag = String::from_utf8(e.name().as_ref().to_vec()).expect("utf8 end tag");
                let popped = tag_stack.pop().expect("unexpected end tag");
                assert_eq!(popped, tag, "mismatched closing tag");

                if let Some(field) = current_field.take() {
                    if field.tag_name == tag
                        && tag_stack
                            .last()
                            .is_some_and(|p| p == "v:sampleDataSet" || p == "sampleDataSet")
                    {
                        if field.is_linked {
                            assert_eq!(
                                field.p_child_count, 0,
                                "LinkedFile <{}> must have zero <p> children",
                                field.tag_name
                            );
                            let trimmed = field.direct_text.trim();
                            if !trimmed.is_empty() {
                                assert!(
                                    !trimmed.contains('\\'),
                                    "LinkedFile <{}> path must use forward slashes: {trimmed}",
                                    field.tag_name
                                );
                                assert!(
                                    trimmed.starts_with("imagens/")
                                        || trimmed.starts_with("file:///"),
                                    "LinkedFile <{}> path must be imagens/... or file:///...: {trimmed}",
                                    field.tag_name
                                );
                            }
                        } else if field.is_text {
                            assert!(
                                field.direct_text.trim().is_empty(),
                                "Text field <{}> must not contain raw text outside <p>: {:?}",
                                field.tag_name,
                                field.direct_text
                            );
                            assert!(
                                field.p_child_count >= 1,
                                "Text field <{}> must wrap content in <p>...</p>",
                                field.tag_name
                            );
                        }
                    } else {
                        current_field = Some(field);
                    }
                }
            }
            Event::Eof => break,
            _ => {}
        }
    }

    assert!(tag_stack.is_empty(), "unclosed XML tags: {tag_stack:?}");
    assert!(saw_decl, "missing <?xml ...?> declaration");
    assert!(saw_doctype, "missing <!DOCTYPE svg ...>");
    assert_eq!(
        dataset_count, expected_datasets,
        "dataset count mismatch"
    );
}

pub fn generate_synthetic_photo_dir(dir: &Path, count: usize) -> Vec<PathBuf> {
    std::fs::create_dir_all(dir).expect("create synthetic photo dir");
    let mut paths = Vec::with_capacity(count);
    for i in 1..=count {
        let (ext, bytes) = if i % 10 == 0 {
            ("png", MINIMAL_PNG_2X2)
        } else if i % 10 == 9 {
            ("tiff", MINIMAL_TIFF_2X2)
        } else {
            ("jpg", MINIMAL_JPEG_2X2)
        };
        let path = dir.join(format!("Pessoa_{i:04}.{ext}"));
        std::fs::write(&path, bytes).expect("write synthetic photo");
        paths.push(path);
    }
    paths
}

pub fn generate_non_square_png(path: &Path, width: u32, height: u32) {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).expect("create parent dir");
    }
    let img = image::RgbaImage::from_fn(width, height, |x, y| {
        image::Rgba([(x % 256) as u8, (y % 256) as u8, 0x80, 0xFF])
    });
    img.save_with_format(path, image::ImageFormat::Png)
        .expect("write non-square PNG");
}

pub fn request_thumbnail_blocking(
    services: &AppServices,
    asset_id: &str,
    path: &Path,
) -> AppResult<ThumbnailState> {
    let deadline = Instant::now() + Duration::from_secs(5);
    loop {
        let state = services
            .photo_service
            .get_or_request_thumbnail(asset_id, path)?;
        match state {
            ThumbnailState::Loading => {
                if Instant::now() >= deadline {
                    return Ok(ThumbnailState::Loading);
                }
                std::thread::sleep(Duration::from_millis(5));
            }
            other => return Ok(other),
        }
    }
}

pub fn extract_xml_datasets(xml_str: &str) -> Vec<(String, HashMap<String, String>)> {
    let mut reader = Reader::from_str(xml_str);
    reader.config_mut().check_end_names = true;

    let mut dtd_entities: HashMap<String, String> = HashMap::new();
    let mut tag_stack: Vec<String> = Vec::new();
    let mut datasets: Vec<(String, HashMap<String, String>)> = Vec::new();
    let mut current_dataset: Option<(String, HashMap<String, String>)> = None;
    let mut current_var: Option<String> = None;
    let mut current_text = String::new();
    let mut in_p = false;

    loop {
        match reader.read_event().expect("quick_xml parse error") {
            Event::DocType(dt) => {
                let dt_text = dt.decode().expect("decode DOCTYPE");
                dtd_entities = extract_dtd_entities(&dt_text);
            }
            Event::Start(e) => {
                let tag = String::from_utf8(e.name().as_ref().to_vec()).expect("utf8 tag");
                if tag == "v:sampleDataSet" || tag == "sampleDataSet" {
                    let mut ds_name = String::new();
                    for attr_res in e.attributes() {
                        let attr = attr_res.expect("attr");
                        if attr.key.as_ref() == b"dataSetName" {
                            ds_name = attr
                                .decoded_and_normalized_value_with(
                                    XmlVersion::Implicit1_0,
                                    e.decoder(),
                                    128,
                                    |ent| {
                                        resolve_predefined_entity(ent)
                                            .or_else(|| dtd_entities.get(ent).map(String::as_str))
                                    },
                                )
                                .expect("unescape dataSetName")
                                .into_owned();
                        }
                    }
                    current_dataset = Some((ds_name, HashMap::new()));
                } else if current_dataset.is_some()
                    && tag_stack
                        .last()
                        .is_some_and(|p| p == "v:sampleDataSet" || p == "sampleDataSet")
                {
                    current_var = Some(tag.clone());
                    current_text.clear();
                    in_p = false;
                } else if current_var.is_some() && tag == "p" {
                    in_p = true;
                }
                tag_stack.push(tag);
            }
            Event::Empty(e) => {
                let tag = String::from_utf8(e.name().as_ref().to_vec()).expect("utf8 tag");
                if current_dataset.is_some()
                    && tag_stack
                        .last()
                        .is_some_and(|p| p == "v:sampleDataSet" || p == "sampleDataSet")
                {
                    if let Some((_, map)) = current_dataset.as_mut() {
                        map.insert(tag, String::new());
                    }
                }
            }
            Event::Text(t) => {
                if current_var.is_some()
                    && (in_p
                        || tag_stack.last().map(String::as_str)
                            == current_var.as_deref())
                {
                    let txt = t.xml10_content().expect("xml10_content");
                    current_text.push_str(&txt);
                }
            }
            Event::GeneralRef(r) => {
                if current_var.is_some()
                    && (in_p
                        || tag_stack.last().map(String::as_str)
                            == current_var.as_deref())
                {
                    if r.is_char_ref() {
                        if let Some(ch) = r.resolve_char_ref().expect("char ref") {
                            current_text.push(ch);
                        }
                    } else {
                        let name = r.decode().expect("entity name");
                        if let Some(val) = resolve_predefined_entity(&name)
                            .or_else(|| dtd_entities.get(name.as_ref()).map(String::as_str))
                        {
                            current_text.push_str(val);
                        }
                    }
                }
            }
            Event::End(e) => {
                let tag = String::from_utf8(e.name().as_ref().to_vec()).expect("utf8 end tag");
                tag_stack.pop();
                if tag == "p" && in_p {
                    in_p = false;
                } else if current_var.as_deref() == Some(tag.as_str())
                    && tag_stack
                        .last()
                        .is_some_and(|p| p == "v:sampleDataSet" || p == "sampleDataSet")
                {
                    if let (Some(var_name), Some((_, map))) =
                        (current_var.take(), current_dataset.as_mut())
                    {
                        map.insert(var_name, current_text.clone());
                    }
                    current_text.clear();
                } else if (tag == "v:sampleDataSet" || tag == "sampleDataSet")
                    && current_dataset.is_some()
                {
                    datasets.push(current_dataset.take().unwrap());
                }
            }
            Event::Eof => break,
            _ => {}
        }
    }

    datasets
}
