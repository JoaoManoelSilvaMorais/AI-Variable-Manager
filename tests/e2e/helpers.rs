pub fn seed_records_and_values(
    services: &AppServices,
    project_id: &str,
    rows: &[(String, Vec<(&Variable, &str)>)],
) -> Vec<Record> {
    let now = utc_now_rfc3339();
    let mut records = Vec::with_capacity(rows.len());
    let mut values = Vec::new();
    for (idx, (dataset_name, cells)) in rows.iter().enumerate() {
        let rec_id = uuid::Uuid::new_v4().to_string();
        records.push(Record {
            id: rec_id.clone(),
            project_id: project_id.to_string(),
            dataset_name: dataset_name.clone(),
            sort_order: idx,
            created_at: now.clone(),
            updated_at: now.clone(),
        });
        for (var, text) in cells {
            values.push(RecordValue::new_text(&rec_id, &var.id, *text));
        }
    }
    services
        .project_repo
        .upsert_records_and_values(project_id, &records, &values)
        .expect("seed records and values");
    records
}

