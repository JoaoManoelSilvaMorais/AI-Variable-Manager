pub struct TestEnv {
    pub temp_dir: TempDir,
    pub db_path: PathBuf,
    pub services: AppServices,
}

impl TestEnv {
    pub fn new() -> Self {
        let temp_dir = TempDir::new().expect("create TempDir");
        let db_path = temp_dir.path().join("app.db");
        let services = AppServices::new_with_db_path(&db_path).expect("init AppServices");
        Self {
            temp_dir,
            db_path,
            services,
        }
    }

    pub fn path(&self) -> &Path {
        self.temp_dir.path()
    }

    pub fn reopen(&self) -> AppServices {
        AppServices::new_with_db_path(&self.db_path).expect("reopen AppServices")
    }

    #[allow(dead_code)]
    pub fn reopen_into(&mut self) {
        self.services = AppServices::new_with_db_path(&self.db_path).expect("reopen AppServices");
    }

    pub fn copy_fixture_file(&self, rel_fixture: &str, dest_rel: &str) -> PathBuf {
        let src = fixture_path(rel_fixture);
        let dst = self.temp_dir.path().join(dest_rel);
        if let Some(parent) = dst.parent() {
            std::fs::create_dir_all(parent).expect("create parent dir");
        }
        std::fs::copy(&src, &dst).expect("copy fixture file");
        dst
    }

    pub fn copy_fixtures_images_to(&self, dest_subdir: &str) -> PathBuf {
        let src_root = fixtures_dir().join("images");
        let dst_root = self.temp_dir.path().join(dest_subdir);
        copy_dir_recursive(&src_root, &dst_root);
        dst_root
    }
}

pub fn copy_dir_recursive(src: &Path, dst: &Path) {
    std::fs::create_dir_all(dst).expect("create target directory");
    for entry_res in std::fs::read_dir(src).expect("read source directory") {
        let entry = entry_res.expect("read dir entry");
        let src_path = entry.path();
        let dst_path = dst.join(entry.file_name());
        if src_path.is_dir() {
            copy_dir_recursive(&src_path, &dst_path);
        } else {
            std::fs::copy(&src_path, &dst_path).expect("copy file");
        }
    }
}

